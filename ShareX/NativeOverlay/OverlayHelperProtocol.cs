/// <summary>Private runtime-directory files, created with their final permissions atomically.
/// File names are generated by the parent; helpers never accept arbitrary result paths.</summary>
internal static class OverlayPixels
{
    public static FileStream Create(string path) => new(path, new FileStreamOptions
    {
        Mode = FileMode.CreateNew, Access = FileAccess.Write, Share = FileShare.Read,
        UnixCreateMode = UnixFileMode.UserRead | UnixFileMode.UserWrite
    });
    public static void Write(string path, SKBitmap image)
    {
        if (image.ColorType != SKColorType.Bgra8888) throw new IOException("Expected BGRA screenshot.");
        using var stream = Create(path);
        using var writer = new BinaryWriter(stream);
        writer.Write(0x53584f56); writer.Write(image.Width); writer.Write(image.Height); writer.Write(image.RowBytes);
        byte[] buffer = new byte[65536];
        int total = checked(image.RowBytes * image.Height);
        for (int offset = 0; offset < total;)
        {
            int count = Math.Min(buffer.Length, total - offset);
            Marshal.Copy(image.GetPixels() + offset, buffer, 0, count);
            stream.Write(buffer, 0, count); offset += count;
        }
    }
    public static SKBitmap Read(string path)
    {
        using var stream = File.OpenRead(path);
        using var reader = new BinaryReader(stream);
        if (reader.ReadInt32() != 0x53584f56) throw new IOException("Invalid overlay image header.");
        int width = reader.ReadInt32(), height = reader.ReadInt32(), stride = reader.ReadInt32();
        long length = (long)stride * height;
        if (width <= 0 || height <= 0 || width > 32768 || height > 32768 || stride != (long)width * 4 ||
            length > 1024L * 1024 * 1024 || stream.Length != 16 + length) throw new IOException("Invalid overlay image dimensions.");
        var image = new SKBitmap(width, height, SKColorType.Bgra8888, SKAlphaType.Premul);
        try
        {
            byte[] buffer = new byte[65536];
            for (int offset = 0; offset < length;)
            {
                int count = (int)Math.Min(buffer.Length, length - offset);
                stream.ReadExactly(buffer.AsSpan(0, count));
                Marshal.Copy(buffer, 0, image.GetPixels() + offset, count); offset += count;
            }
            return image;
        }
        catch { image.Dispose(); throw; }
    }
    public static string CreateDirectory()
    {
        string runtime = Environment.GetEnvironmentVariable("XDG_RUNTIME_DIR") ?? throw new IOException("XDG_RUNTIME_DIR is unset.");
        if (!Path.IsPathFullyQualified(runtime) || !Directory.Exists(runtime)) throw new IOException("Invalid XDG_RUNTIME_DIR.");
        string directory = Path.Combine(runtime, "sharex-overlay-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute);
        return directory;
    }
}
