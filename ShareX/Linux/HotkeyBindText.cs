using ShareX.HelpersLib;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ShareX;

internal enum BindDialect
{
    HyprlandLua,
    HyprlandConf,
    Sway,
    Niri,
    Gnome,
    Kde
}

/// <summary>Generates compositor configuration lines for the user's ShareX hotkeys.</summary>
internal static class HotkeyBindText
{
    /// <param name="portal">
    /// true: trigger the shortcuts ShareX registered through the desktop portal (<c>global</c> dispatcher, Hyprland only).
    /// false: run <c>sharex -Action</c>, which works on every compositor and does not need the portal.
    /// </param>
    public static string Build(IEnumerable<HotkeySettings> hotkeys, BindDialect dialect, bool portal, string launcher = "sharex", ISet<string> takenKeys = null)
    {
        List<HotkeySettings> list = hotkeys.Where(x => x?.HotkeyInfo != null && x.TaskSettings != null).ToList();
        HotkeyNames.Assign(list);

        if (dialect != BindDialect.HyprlandLua && dialect != BindDialect.HyprlandConf)
        {
            portal = false;
        }

        if (dialect == BindDialect.Kde)
        {
            return "# KDE Plasma: no key binds to add. ShareX registers its hotkeys with the desktop's GlobalShortcuts portal, so they appear in\n" +
                   "# System Settings -> Keyboard -> Shortcuts under \"ShareX\", where you can assign the keys you want to each action.\n" +
                   "# Spectacle owns Print by default: remove it there first (Shortcuts -> Spectacle) or choose other keys.\n" +
                   "# Command alternative (Shortcuts -> Add Command): sharex -RectangleRegion, sharex -PrintScreen, sharex -ActiveWindow, ...\n";
        }

        if (dialect == BindDialect.Gnome)
        {
            return BuildGnome(list, launcher);
        }

        string comment = dialect == BindDialect.Niri ? "//" : dialect == BindDialect.HyprlandLua ? "--" : "#";
        StringBuilder text = new();
        text.AppendLine($"{comment} ShareX hotkeys ({(portal ? "desktop portal global shortcuts" : "command line actions")}); generated by: sharex --print-binds");
        text.AppendLine($"{comment} Remove the keys you already use for something else. Do not bind the same key through both methods.");

        foreach (HotkeySettings hotkey in list)
        {
            HotkeyInfo info = hotkey.HotkeyInfo;

            if (hotkey.TaskSettings.Job == HotkeyType.None || !info.IsValidHotkey || LinuxKeyNames.KeySym(info.KeyCode) is not string key)
            {
                continue;
            }

            string job = hotkey.TaskSettings.Job.ToString();
            List<string> mods = new();
            bool sway = dialect == BindDialect.Sway, niri = dialect == BindDialect.Niri;
            if (info.Win) mods.Add(sway ? "Mod4" : niri ? "Super" : "SUPER");
            if (info.Control) mods.Add(sway || niri ? "Ctrl" : "CTRL");
            if (info.Alt) mods.Add(sway ? "Mod1" : niri ? "Alt" : "ALT");
            if (info.Shift) mods.Add(sway || niri ? "Shift" : "SHIFT");

            string target = portal ? info.Name : null;
            string prefix = "";

            if (takenKeys != null && takenKeys.Contains(Normalize(mods, key)))
            {
                // Keep the line for reference but don't let it override or duplicate a key the user already uses.
                prefix = dialect == BindDialect.HyprlandLua ? "-- skipped, key already bound in your config: " : "# skipped, key already bound in your config: ";
            }

            text.AppendLine(prefix + dialect switch
            {
                BindDialect.HyprlandLua => $"hl.bind(\"{string.Join(" + ", mods.Append(key))}\", " +
                    (portal ? $"hl.dsp.global(\"sharex:{target}\")" : $"hl.dsp.exec_cmd(\"{launcher} -{job}\")") + ")  -- " + info.Description,
                BindDialect.HyprlandConf => $"bind = {string.Join(" ", mods)}, {key}, " +
                    (portal ? $"global, sharex:{target}" : $"exec, {launcher} -{job}") + "  # " + info.Description,
                BindDialect.Niri => $"{string.Join("+", mods.Append(key))} {{ spawn \"{launcher}\" \"-{job}\"; }}  // {info.Description}",
                _ => $"bindsym {string.Join("+", mods.Append(key))} exec {launcher} -{job}  # {info.Description}"
            });
        }

        if (dialect == BindDialect.Niri)
        {
            text.Insert(0, "// Put the lines below inside the existing  binds { ... }  block of ~/.config/niri/config.kdl (niri has no way for an app to add them),\n" +
                           "// then niri reloads the config by itself. niri needs xwayland-satellite installed for ShareX's windows.\n");
        }

        return text.ToString();
    }

    private static string BuildGnome(List<HotkeySettings> list, string launcher)
    {
        static string Clean(string value) => new string(value.Where(c => c != '\'' && c != '"' && c != '\\' && c != '$' && c != '`' && c != '\n').ToArray());

        StringBuilder text = new();
        text.AppendLine("#!/bin/sh");
        text.AppendLine("# ShareX hotkeys for GNOME as custom keyboard shortcuts. Run:  sharex --print-binds gnome | sh");
        text.AppendLine("# (GNOME 48 and newer can also use the GlobalShortcuts portal, but custom shortcuts work everywhere.) Re-running updates the same entries.");
        text.AppendLine("base=/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings");
        text.AppendLine("schema=org.gnome.settings-daemon.plugins.media-keys.custom-keybinding");
        text.AppendLine("list=$(gsettings get org.gnome.settings-daemon.plugins.media-keys custom-keybindings) || exit 1");
        text.AppendLine("list=${list#@as }");
        text.AppendLine("add() {");
        text.AppendLine("    path=\"$base/sharex-$1/\"");
        text.AppendLine("    gsettings set \"$schema:$path\" name \"'$2'\"");
        text.AppendLine("    gsettings set \"$schema:$path\" command \"'$3'\"");
        text.AppendLine("    gsettings set \"$schema:$path\" binding \"'$4'\"");
        text.AppendLine("    case \"$list\" in");
        text.AppendLine("        *\"'$path'\"*) ;;");
        text.AppendLine("        \"[]\") list=\"['$path']\" ;;");
        text.AppendLine("        *) list=\"${list%]}, '$path']\" ;;");
        text.AppendLine("    esac");
        text.AppendLine("}");

        foreach (HotkeySettings hotkey in list)
        {
            HotkeyInfo info = hotkey.HotkeyInfo;
            if (hotkey.TaskSettings.Job == HotkeyType.None || !info.IsValidHotkey || LinuxKeyNames.KeySym(info.KeyCode) is not string key) continue;

            string accel = (info.Win ? "<Super>" : "") + (info.Control ? "<Control>" : "") + (info.Alt ? "<Alt>" : "") + (info.Shift ? "<Shift>" : "") + key;
            text.AppendLine($"add {hotkey.HotkeyInfo.Name} \"{Clean("ShareX: " + info.Description)}\" \"{Clean(launcher)} -{hotkey.TaskSettings.Job}\" \"{accel}\"");
        }

        text.AppendLine("gsettings set org.gnome.settings-daemon.plugins.media-keys custom-keybindings \"$list\"");
        return text.ToString();
    }

    private static string ModName(string mod) => mod.Trim().ToUpperInvariant() switch
    {
        "SUPER" or "MOD4" or "WIN" or "LOGO" or "$MAINMOD" or "MAINMOD" => "SUPER",
        "CTRL" or "CONTROL" => "CTRL",
        "ALT" or "MOD1" => "ALT",
        var other => other
    };

    /// <summary>Canonical form of a key combination, used to detect keys that are already bound.</summary>
    public static string Normalize(IEnumerable<string> mods, string key)
    {
        return string.Join("+", mods.Select(ModName).Where(x => x.Length > 0).OrderBy(x => x, StringComparer.Ordinal).Append(key.Trim().ToUpperInvariant()));
    }

    /// <summary>Implements <c>sharex --print-binds [hyprland|hyprland-conf|sway] [--global]</c>.</summary>
    public static int PrintBinds(string[] args)
    {
        string dialectName = args.FirstOrDefault(x => !x.StartsWith("-")) ?? "hyprland";
        BindDialect dialect = dialectName.ToLowerInvariant() switch
        {
            "hyprland" or "hyprland-lua" or "lua" => BindDialect.HyprlandLua,
            "hyprland-conf" or "conf" => BindDialect.HyprlandConf,
            "sway" => BindDialect.Sway,
            "niri" => BindDialect.Niri,
            "gnome" => BindDialect.Gnome,
            "kde" or "plasma" => BindDialect.Kde,
            _ => throw new ArgumentException("Unknown format '" + dialectName + "'. Use hyprland, hyprland-conf, sway, niri, gnome or kde.")
        };

        string path = System.IO.Path.Combine(AppPaths.PersonalFolder, "HotkeysConfig.json");
        HotkeysConfig config = System.IO.File.Exists(path) ? HotkeysConfig.Load(path, null, false) : new HotkeysConfig();

        string home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        string self = System.IO.Path.Combine(home, ".local", "bin", "sharex");
        // niri and GNOME start the command without a shell, so they need the real path instead of "~".
        bool noShell = dialect is BindDialect.Niri or BindDialect.Gnome;
        string launcher = System.IO.File.Exists(self) ? (noShell ? self : "~/.local/bin/sharex") : "sharex";

        Console.Write(Build(config.Hotkeys, dialect, args.Contains("--global"), launcher));
        return 0;
    }
}
