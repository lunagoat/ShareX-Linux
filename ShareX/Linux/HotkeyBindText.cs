using ShareX.HelpersLib;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ShareX;

internal enum BindDialect
{
    HyprlandLua,
    HyprlandConf,
    Sway
}

/// <summary>Generates compositor configuration lines for the user's ShareX hotkeys.</summary>
internal static class HotkeyBindText
{
    /// <param name="portal">
    /// true: trigger the shortcuts ShareX registered through the desktop portal (<c>global</c> dispatcher, Hyprland only).
    /// false: run <c>sharex -Action</c>, which works on every compositor and does not need the portal.
    /// </param>
    public static string Build(IEnumerable<HotkeySettings> hotkeys, BindDialect dialect, bool portal, string launcher = "sharex", ISet<string> takenKeys = null)
    {
        List<HotkeySettings> list = hotkeys.Where(x => x?.HotkeyInfo != null && x.TaskSettings != null).ToList();
        HotkeyNames.Assign(list);

        if (dialect == BindDialect.Sway)
        {
            portal = false;
        }

        string comment = dialect == BindDialect.HyprlandLua ? "--" : "#";
        StringBuilder text = new();
        text.AppendLine($"{comment} ShareX hotkeys ({(portal ? "desktop portal global shortcuts" : "command line actions")}); generated by: sharex --print-binds");
        text.AppendLine($"{comment} Remove the keys you already use for something else. Do not bind the same key through both methods.");

        foreach (HotkeySettings hotkey in list)
        {
            HotkeyInfo info = hotkey.HotkeyInfo;

            if (hotkey.TaskSettings.Job == HotkeyType.None || !info.IsValidHotkey || LinuxKeyNames.KeySym(info.KeyCode) is not string key)
            {
                continue;
            }

            string job = hotkey.TaskSettings.Job.ToString();
            List<string> mods = new();
            if (info.Win) mods.Add(dialect == BindDialect.Sway ? "Mod4" : "SUPER");
            if (info.Control) mods.Add(dialect == BindDialect.Sway ? "Ctrl" : "CTRL");
            if (info.Alt) mods.Add(dialect == BindDialect.Sway ? "Mod1" : "ALT");
            if (info.Shift) mods.Add(dialect == BindDialect.Sway ? "Shift" : "SHIFT");

            string target = portal ? info.Name : null;
            string prefix = "";

            if (takenKeys != null && takenKeys.Contains(Normalize(mods, key)))
            {
                // Keep the line for reference but don't let it override or duplicate a key the user already uses.
                prefix = dialect == BindDialect.HyprlandLua ? "-- skipped, key already bound in your config: " : "# skipped, key already bound in your config: ";
            }

            text.AppendLine(prefix + dialect switch
            {
                BindDialect.HyprlandLua => $"hl.bind(\"{string.Join(" + ", mods.Append(key))}\", " +
                    (portal ? $"hl.dsp.global(\"sharex:{target}\")" : $"hl.dsp.exec_cmd(\"{launcher} -{job}\")") + ")  -- " + info.Description,
                BindDialect.HyprlandConf => $"bind = {string.Join(" ", mods)}, {key}, " +
                    (portal ? $"global, sharex:{target}" : $"exec, {launcher} -{job}") + "  # " + info.Description,
                _ => $"bindsym {string.Join("+", mods.Append(key))} exec {launcher} -{job}  # {info.Description}"
            });
        }

        return text.ToString();
    }

    private static string ModName(string mod) => mod.Trim().ToUpperInvariant() switch
    {
        "SUPER" or "MOD4" or "WIN" or "LOGO" or "$MAINMOD" or "MAINMOD" => "SUPER",
        "CTRL" or "CONTROL" => "CTRL",
        "ALT" or "MOD1" => "ALT",
        var other => other
    };

    /// <summary>Canonical form of a key combination, used to detect keys that are already bound.</summary>
    public static string Normalize(IEnumerable<string> mods, string key)
    {
        return string.Join("+", mods.Select(ModName).Where(x => x.Length > 0).OrderBy(x => x, StringComparer.Ordinal).Append(key.Trim().ToUpperInvariant()));
    }

    /// <summary>Implements <c>sharex --print-binds [hyprland|hyprland-conf|sway] [--global]</c>.</summary>
    public static int PrintBinds(string[] args)
    {
        string dialectName = args.FirstOrDefault(x => !x.StartsWith("-")) ?? "hyprland";
        BindDialect dialect = dialectName.ToLowerInvariant() switch
        {
            "hyprland" or "hyprland-lua" or "lua" => BindDialect.HyprlandLua,
            "hyprland-conf" or "conf" => BindDialect.HyprlandConf,
            "sway" => BindDialect.Sway,
            _ => throw new ArgumentException("Unknown format '" + dialectName + "'. Use hyprland, hyprland-conf or sway.")
        };

        string path = System.IO.Path.Combine(AppPaths.PersonalFolder, "HotkeysConfig.json");
        HotkeysConfig config = System.IO.File.Exists(path) ? HotkeysConfig.Load(path, null, false) : new HotkeysConfig();

        string home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        string self = System.IO.Path.Combine(home, ".local", "bin", "sharex");
        string launcher = System.IO.File.Exists(self) ? "~/.local/bin/sharex" : "sharex";

        Console.Write(Build(config.Hotkeys, dialect, args.Contains("--global"), launcher));
        return 0;
    }
}
