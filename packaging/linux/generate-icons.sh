#!/usr/bin/env bash
# Regenerate the Linux hicolor icon theme from the Windows icon resources.
#
#   packaging/linux/generate-icons.sh
#
# Source of truth: ShareX/ShareX_Icon.ico (contains 16x16, 32x32, 48x48 and 256x256
# frames). The largest frame is used as the master and downscaled with Lanczos.
# The generated PNGs are checked into git so that distributions do not need
# ImageMagick at build time; re-run this script after changing the icon.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$root/ShareX/ShareX_Icon.ico"
out="$root/packaging/linux/icons"

if ! command -v magick >/dev/null 2>&1; then
    echo "error: ImageMagick 7 ('magick') is required to generate the icons" >&2
    exit 1
fi

if [ ! -f "$src" ]; then
    echo "error: icon source not found: $src" >&2
    exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Pick the largest frame of the .ico (frame order is not part of the ICO spec).
frame="$(magick identify -format '%s %w\n' "$src" | sort -k2 -n | tail -n1 | cut -d' ' -f1)"
echo "extracting frame $frame from $src"
magick "$src[$frame]" -background none -alpha on -strip "$tmp/sharex-256.png"

sizes="16 24 32 48 64 128 256"

for size in $sizes; do
    dir="$out/hicolor/${size}x${size}/apps"
    mkdir -p "$dir"
    magick "$tmp/sharex-256.png" -filter Lanczos -resize "${size}x${size}" -strip "$dir/sharex.png"
    echo "  ${size}x${size}/apps/sharex.png"
done

# Upstream does not ship a vector logo, so the "scalable" icon is an SVG wrapper
# around the 256x256 raster master. It renders crisply at the sizes desktops use
# and keeps icon lookup working for themes that only look in scalable/.
mkdir -p "$out/hicolor/scalable/apps"
{
    printf '%s\n' '<?xml version="1.0" encoding="UTF-8" standalone="no"?>'
    printf '%s\n' '<!-- Generated by packaging/linux/generate-icons.sh - ShareX logo, GPL-3.0-only -->'
    printf '%s\n' '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"'
    printf '%s\n' '     width="256" height="256" viewBox="0 0 256 256" version="1.1">'
    printf '%s\n' '  <title>ShareX</title>'
    printf '  <image width="256" height="256" xlink:href="data:image/png;base64,'
    base64 -w0 "$tmp/sharex-256.png"
    printf '%s\n' '"/>'
    printf '%s\n' '</svg>'
} >"$out/hicolor/scalable/apps/sharex.svg"

echo "  scalable/apps/sharex.svg"
echo "done: $out"
